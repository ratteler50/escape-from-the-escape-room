// Generates docs/handbook.md: every section of the Employee Handbook, with Dana's comment on it and
// the writers' notes, from the one list in src/content/handbookSections.ts.
// Run with `npm run handbook`. src/content/handbook.test.ts fails if docs/handbook.md is out of date.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { revisedSection14, sections, type HandbookSection } from '../src/content/handbookSections.ts';

const OUT = join(import.meta.dirname, '..', 'docs', 'handbook.md');

/** A table cell: one line, with pipes escaped. */
const cell = (text: string | undefined) => (text ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const row = (s: HandbookSection) => `| ${cell(s.section)} | ${cell(s.rule)} | ${cell(s.aside)} | ${cell(s.note)} |`;

export function generateHandbook(): string {
  return [
    '# The Employee Handbook',
    '',
    'Every section of the Escape-O-Rama Employee Handbook that the game quotes, with the comment Dana',
    'makes when reading it out, and notes for writers. Each section means one thing everywhere: check',
    'here before quoting one, and add new ones to `src/content/handbookSections.ts`.',
    '',
    'Generated by `npm run handbook` from `src/content/handbookSections.ts`; a test fails when this file',
    'is out of date. It runs to about 400 sections; these are the ones the game quotes, and the big',
    'numbers are there to say so.',
    '',
    '| Section | Rule | Dana says | Note |',
    '|---------|------|-----------|------|',
    ...sections.map(row),
    '',
    '## The revised Section 14',
    '',
    'Stapled over the old one, and found only by showing Kyle the Handbook (slice 30).',
    '',
    '| Section | Rule | Dana says | Note |',
    '|---------|------|-----------|------|',
    row(revisedSection14),
    '',
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(OUT, generateHandbook());
  console.log(`Wrote ${OUT}: ${sections.length} sections.`);
}
