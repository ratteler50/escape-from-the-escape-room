// Generates docs/drafts.md: every line marked `// DRAFT:` in the content, grouped by file and speaker,
// so the developer can punch them up in one sitting (docs/slices/17-polish.md).
// Run with `npm run drafts`. src/content/drafts.test.ts fails if docs/drafts.md is out of date.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'docs', 'drafts.md');

/** Content files in play order, with the heading each gets. Any other content file follows, by name. */
const FILES: [string, string][] = [
  ['lair.ts', "The Lich's Lair"],
  ['reginald.ts', 'Reginald'],
  ['giftShop.ts', 'The Gift Shop'],
  ['kyle.ts', 'Kyle'],
  ['mordecai.ts', 'Mordecai'],
  ['breakRoom.ts', 'The Break Room'],
  ['finale.ts', 'The finale'],
  ['world.ts', 'Fallback lines'],
];

/** The call or key that starts a spoken line, and who speaks it (content's dsl helpers and shorthands). */
const SPEAKERS: [RegExp, string][] = [
  [/\bR\(/, 'Reginald'],
  [/\bK\(/, 'Kyle'],
  [/\bM\(/, 'Mordecai'],
  [/\bline\(\s*['"](\w+)['"]\s*,/, '$1'],
  [/\btext:/, 'Dana (option)'],
  [/\bsays?\(/, 'Dana'],
  // An item's look line is a bare string; a hotspot's `look: says(…)` is Dana speaking.
  [/\blook:\s*(?=['"`])/, 'Look'],
];

interface Draft {
  file: string;
  line: number;
  speaker: string;
  text: string;
}

/** The first string literal on the line ('…', "…" or `…`), unescaped. */
function firstString(source: string): string | undefined {
  const match = /(['"`])((?:\\.|(?!\1).)*)\1/.exec(source);
  return match?.[2]?.replace(/\\(.)/g, '$1');
}

/** Who speaks the line and what they say: the first string after the earliest speaking call or key. */
function spoken(source: string): { speaker: string; text: string } | undefined {
  let best: { at: number; speaker: string; rest: string } | undefined;
  for (const [pattern, name] of SPEAKERS) {
    const match = pattern.exec(source);
    if (match && (!best || match.index < best.at)) {
      best = { at: match.index, speaker: name.replace('$1', match[1] ?? ''), rest: source.slice(match.index + match[0].length) };
    }
  }
  // A bare string (e.g. a fallback line in a list) has no call in front of it.
  const text = firstString(best ? best.rest : source);
  return text === undefined ? undefined : { speaker: best?.speaker ?? 'Dana', text };
}

/** Finds drafts in one file: the first spoken line after each `// DRAFT:` marker. */
export function draftsIn(file: string, source: string): Draft[] {
  const lines = source.split('\n');
  const drafts: Draft[] = [];
  lines.forEach((l, i) => {
    if (!l.includes('// DRAFT:')) return;
    for (let j = i + 1; j < Math.min(i + 5, lines.length); j++) {
      const found = spoken(lines[j]!);
      if (found) {
        drafts.push({ file, line: j + 1, ...found });
        return;
      }
    }
  });
  return drafts;
}

function contentFiles(): [string, string][] {
  const known = new Set(FILES.map(([file]) => file));
  const others = readdirSync(join(ROOT, 'src', 'content'))
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && !known.has(f))
    .sort()
    .map((f): [string, string] => [f, f]);
  return [...FILES, ...others];
}

export function generateDrafts(): string {
  const files = contentFiles();
  const sections = files.map(([file, heading]) => {
    const drafts = draftsIn(file, readFileSync(join(ROOT, 'src', 'content', file), 'utf8'));
    if (drafts.length === 0) return '';
    const rows = drafts.map((d) => `| \`${d.file}:${d.line}\` | ${d.speaker} | ${d.text.replace(/\|/g, '\\|')} |`);
    return [`## ${heading} (${drafts.length})`, '', '| Where | Who | Line |', '|---|---|---|', ...rows, ''].join('\n');
  });
  const total = files.reduce((n, [file]) => n + draftsIn(file, readFileSync(join(ROOT, 'src', 'content', file), 'utf8')).length, 0);
  return [
    '# Draft lines',
    '',
    `Every line marked \`// DRAFT:\` in the game's content: ${total} lines, grouped by file. Punch one up by`,
    'editing it at the file and line shown, then delete its `// DRAFT:` marker once you are happy with it.',
    '',
    'Generated by `npm run drafts`; a test fails when this file is out of date. "Look" is a look line',
    'for an item; "Dana (option)" is a line Dana says when the player picks it in a conversation.',
    '',
    ...sections.filter(Boolean),
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(OUT, generateDrafts());
  console.log(`Wrote ${OUT}`);
}
